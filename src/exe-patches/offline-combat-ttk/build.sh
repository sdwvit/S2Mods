#!/usr/bin/env bash
# Bake mutant attacks from the GameLite cfgs into attacks.h, then build the cave (entry.S + cave.c) into flat position-independent x86-64 code (Microsoft x64 ABI)
# and embed it, with its import-stub offsets, between the CAVE markers of ../offline-combat-ttk.py.
# Needs gcc and binutils (Linux). The .py stays self-contained, so players need only Python.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="$(mktemp -d)"
trap 'rm -rf "$out"' EXIT

CFLAGS=(-Os -mabi=ms -ffreestanding -fno-builtin -nostdlib -fPIE -fno-plt -fvisibility=hidden
  -fno-stack-protector -fno-asynchronous-unwind-tables -fno-jump-tables -fcf-protection=none
  -mno-red-zone -fno-tree-vectorize -Wall -Wextra -Werror)
python3 "$here/gen_attacks.py" "$here/../../../GameLite/GameData" "$here/attacks.h"
gcc "${CFLAGS[@]}" -c "$here/cave.c" -o "$out/cave.o"
gcc -c "$here/entry.S" -o "$out/entry.o"

cat > "$out/cave.ld" <<'EOF'
SECTIONS {
  . = 0;
  .cave : { *(.text.entry) *(.text .text.*) *(.rodata .rodata.*) }
  /DISCARD/ : { *(.comment) *(.note*) *(.eh_frame*) }
}
EOF
ld -nostdlib -T "$out/cave.ld" -o "$out/cave.elf" "$out/entry.o" "$out/cave.o"

# everything must live in .cave: no writable data, no leftover sections
extra="$(objdump -h "$out/cave.elf" | awk '$1 ~ /^[0-9]+$/ && $2 != ".cave" && $3 != "00000000" {print $2}')"
[ -z "$extra" ] || { echo "unexpected sections: $extra" >&2; exit 1; }
objcopy -O binary -j .cave "$out/cave.elf" "$out/cave.bin"

python3 - "$out/cave.elf" "$out/cave.bin" "$here/../offline-combat-ttk.py" <<'EOF'
import re, subprocess, sys
elf, binf, py = sys.argv[1:]
blob = open(binf, "rb").read()
syms = {}
for line in subprocess.run(["nm", elf], capture_output=True, text=True, check=True).stdout.splitlines():
    a, _, n = line.split()
    syms[n] = int(a, 16)
stubs = ["name_addref", "proto_lookup", "weapon_attr", "weapon_settings", "set_hp",
         "p_srand_seed", "p_item_pool", "p_name_pool"]
assert syms["entry"] == 0, "entry must be at offset 0"
lines = ["# BEGIN CAVE (generated by offline-combat-ttk/build.sh; do not edit)",
         f"CAVE_STUBS = {{{', '.join(f'{n!r}: 0x{syms[n]:x}' for n in stubs)}}}",
         "CAVE_CODE = bytes.fromhex("]
hexs = blob.hex()
lines += [f'    "{hexs[i:i + 96]}"' for i in range(0, len(hexs), 96)]
lines += [")", "# END CAVE"]
src = open(py).read()
new, n = re.subn(r"# BEGIN CAVE.*?# END CAVE", lambda _: "\n".join(lines), src, flags=re.S)
assert n == 1, "CAVE markers not found in " + py
open(py, "w").write(new)
print(f"cave: {len(blob)} bytes, embedded in {py}")
EOF
