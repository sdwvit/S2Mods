def steam_roots():
    home = os.path.expanduser("~")
    roots = [
        os.path.join(home, ".steam", "steam"),
        os.path.join(home, ".local", "share", "Steam"),
        os.path.join(home, ".var", "app", "com.valvesoftware.Steam", ".local", "share", "Steam"),
        os.path.join(home, "Library", "Application Support", "Steam"),
    ]
    if os.name == "nt":
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Software\Valve\Steam") as k:
                roots.insert(0, winreg.QueryValueEx(k, "SteamPath")[0])
        except OSError:
            pass
        for env in ("ProgramFiles(x86)", "ProgramFiles"):
            if os.environ.get(env):
                roots.append(os.path.join(os.environ[env], "Steam"))
    return roots


def steam_game_folders():
    """Game folder in every Steam library listed in libraryfolders.vdf."""
    seen = set()
    for root in steam_roots():
        libs = [root]
        vdf = os.path.join(root, "steamapps", "libraryfolders.vdf")
        if os.path.exists(vdf):
            text = open(vdf, encoding="utf-8", errors="replace").read()
            libs += [p.replace("\\\\", "\\") for p in re.findall(r'"path"\s+"([^"]+)"', text)]
        for lib in libs:
            folder = os.path.join(lib, "steamapps", "common", GAME_DIR_NAME)
            key = os.path.realpath(folder)
            if key not in seen and os.path.exists(os.path.join(folder, EXE_IN_GAME_FOLDER)):
                seen.add(key)
                yield folder


def default_exe():
    """Find the exe: STALKER2_FOLDER (environment, else the repo .env next to this script), else Steam libraries."""
    folder = os.environ.get("STALKER2_FOLDER")
    if not folder and os.path.exists(REPO_ENV):
        for line in open(REPO_ENV, encoding="utf-8"):
            key, sep, value = line.strip().partition("=")
            if sep and key.strip() == "STALKER2_FOLDER":
                folder = value.strip().strip("\"'")
    if folder:
        return os.path.join(folder, EXE_IN_GAME_FOLDER)
    found = list(steam_game_folders())
    if len(found) > 1:
        sys.exit("several installs found, pass --exe:\n  " + "\n  ".join(found))
    return os.path.join(found[0], EXE_IN_GAME_FOLDER) if found else None


def pat(s):
    return re.compile(b"".join(b"." if t == "??" else re.escape(bytes([int(t, 16)])) for t in s.split()), re.S)


class PE:
    def __init__(self, data):
        self.d = data
        pe = struct.unpack_from("<I", data, 0x3C)[0]
        assert data[pe:pe + 4] == b"PE\0\0", "not a PE file"
        nsec, optsz = struct.unpack_from("<H", data, pe + 6)[0], struct.unpack_from("<H", data, pe + 20)[0]
        opt = pe + 24
        self.base = struct.unpack_from("<Q", data, opt + 24)[0]
        exc_rva, exc_size = struct.unpack_from("<II", data, opt + 112 + 3 * 8)
        self.secs = []
        for i in range(nsec):
            o = opt + optsz + 40 * i
            name = data[o:o + 8].rstrip(b"\0").decode()
            vsize, va, rsize, raw = struct.unpack_from("<IIII", data, o + 8)
            self.secs.append((name, va, vsize, raw, rsize))
        self.text = next(s for s in self.secs if s[0] == ".text")
        exc = self.rva2off(exc_rva)
        self.funcs = sorted(struct.unpack_from("<II", data, exc + 12 * i) for i in range(exc_size // 12))

    def rva2off(self, rva):
        for _, va, vsize, raw, rsize in self.secs:
            if va <= rva < va + min(vsize, rsize):
                return raw + rva - va
        raise ValueError(f"rva 0x{rva:x} not backed by file data")

    def off2rva(self, off):
        for _, va, vsize, raw, rsize in self.secs:
            if raw <= off < raw + rsize:
                return va + off - raw
        raise ValueError(f"offset 0x{off:x} outside sections")

    def va(self, off):
        return self.base + self.off2rva(off)

    def in_text(self, off, n=1):
        _, _, vsize, raw, rsize = self.text
        return raw <= off and off + n <= raw + min(vsize, rsize)

    def in_function(self, rva_lo, rva_hi):
        """True if any .pdata function range overlaps [rva_lo, rva_hi)."""
        return any(b < rva_hi and e > rva_lo for b, e in self.funcs)


def rip_target(pe, off, insn_len, disp_at):
    """File-independent RVA that a rip-relative operand points at."""
    return pe.off2rva(off) + insn_len + struct.unpack_from("<i", pe.d, off + disp_at)[0]


def unique(data, pattern, what):
    hits = [m.start() for m in pat(pattern).finditer(data)]
    if len(hits) != 1:
        sys.exit(f"{what}: pattern found {len(hits)} times (want 1); game update changed the code? exe not written")
    return hits[0]


