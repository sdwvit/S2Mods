def locate_hook(data):
    """(state, rolls_offset); state is 'vanilla' or 'patched'."""
    v = [m.start() + 32 for m in pat(f"{PRE} {ROLLS} {POST}").finditer(data)]
    p = [m.start() + 32 for m in pat(f"{PRE} {HOOK} {POST}").finditer(data)]
    if len(v) == 1 and not p:
        return "vanilla", v[0]
    if len(p) == 1 and not v:
        return "patched", p[0]
    sys.exit(f"duel roll block found vanilla {len(v)}, patched {len(p)} times (want exactly one): "
             "game update, or another patch (e.g. 'higher weight always wins') changed it; exe not written")


def locate_imports(pe, rolls):
    d = pe.d
    rva = {}
    isa = unique(d, IS_ARTIFACT, "IsArtifact")
    rva["p_name_pool"] = rip_target(pe, isa + 0x27, 7, 3)
    rva["name_addref"] = rip_target(pe, isa + 0x2E, 5, 1)
    rva["proto_lookup"] = rip_target(pe, isa + 0x38, 5, 1)
    for name, head in (("name_addref", ADDREF_HEAD), ("proto_lookup", LOOKUP_HEAD)):
        o = pe.rva2off(rva[name])
        if not pat(head).match(d, o):
            sys.exit(f"{name}: IsArtifact calls something unexpected at 0x{pe.base + rva[name]:x}; exe not written")
    rva["set_hp"] = pe.off2rva(unique(d, SET_HP, "unit HP setter"))
    rva["weapon_attr"] = pe.off2rva(unique(d, WEAPON_ATTR, "NPC weapon attributes"))
    rva["weapon_settings"] = pe.off2rva(unique(d, WEAPON_SETTINGS, "character weapon settings"))
    pools = {rip_target(pe, m.start() + 6, 7, 3) for m in pat(ITEM_POOL).finditer(d)}
    if len(pools) != 1:
        sys.exit(f"item pool: {len(pools)} candidates (want 1); exe not written")
    rva["p_item_pool"] = pools.pop()
    rva["p_srand_seed"] = rip_target(pe, rolls + SEED_IMUL, 10, 2)
    return rva


def find_cave(pe, need):
    """File offset of the first 16-aligned run of int3 in .text, outside every function, that fits `need` bytes."""
    _, va, vsize, raw, rsize = pe.text
    for m in re.finditer(rb"\xcc{%d,}" % (need + 32), pe.d[raw:raw + min(vsize, rsize)]):
        start = raw + ((m.start() + 16 + 15) & ~15)  # keep the padding byte before and after
        end = raw + m.end() - 16
        if end - start < need:
            continue
        rva = pe.off2rva(start)
        if not pe.in_function(rva, rva + need):
            return start
    sys.exit("no free int3 run in .text large enough for the cave; exe not written")


def rel32(pe, from_off, insn_len, target_rva):
    return struct.pack("<i", target_rva - (pe.off2rva(from_off) + insn_len))


def build_apply(pe, rolls):
    if "CAVE_CODE" not in globals():
        sys.exit("cave not built: run offline-combat-ttk/build.sh")
    imports = locate_imports(pe, rolls)
    need = CAVE_HDR + len(CAVE_CODE)
    cave = find_cave(pe, need)
    entry = cave + CAVE_HDR
    code = bytearray(CAVE_CODE)
    for name, at in CAVE_STUBS.items():
        if code[at] == 0xE9:  # jmp rel32
            code[at + 1:at + 5] = rel32(pe, entry + at, 5, imports[name])
        elif code[at:at + 3] == b"\x48\x8d\x05":  # lea rax,[rip+rel32]
            code[at + 3:at + 7] = rel32(pe, entry + at, 7, imports[name])
        else:
            sys.exit(f"internal error: stub {name} has unexpected bytes")
    saved = pe.d[rolls:rolls + ROLLS_LEN]
    hdr = CAVE_MAGIC + struct.pack("<II", len(code), len(saved)) + saved
    hdr += b"\xcc" * (CAVE_HDR - len(hdr))
    hook = bytearray.fromhex(HOOK.replace("??", "00"))
    hook[HOOK_CALL + 1:HOOK_CALL + 5] = rel32(pe, rolls + HOOK_CALL, 5, pe.off2rva(entry))
    for name in sorted(imports, key=imports.get):
        print(f"  {name:16} 0x{pe.base + imports[name]:x}")
    print(f"  cave             0x{pe.va(cave):x} ({need} bytes)")
    return [(cave, hdr + bytes(code)), (rolls, bytes(hook))]


def build_revert(pe, rolls):
    entry_rva = pe.off2rva(rolls + HOOK_CALL) + 5 + struct.unpack_from("<i", pe.d, rolls + HOOK_CALL + 1)[0]
    cave = pe.rva2off(entry_rva) - CAVE_HDR
    if pe.d[cave:cave + 8] != CAVE_MAGIC:
        sys.exit(f"hook calls 0x{pe.base + entry_rva:x}, which is not this patch's cave; exe not written")
    code_len, saved_len = struct.unpack_from("<II", pe.d, cave + 8)
    saved = pe.d[cave + 16:cave + 16 + saved_len]
    if saved_len != ROLLS_LEN or not pat(ROLLS).fullmatch(saved):
        sys.exit("saved vanilla bytes in the cave header are damaged; restore the backup instead")
    print(f"  cave             0x{pe.va(cave):x} ({CAVE_HDR + code_len} bytes) -> int3")
    return [(rolls, saved), (cave, b"\xcc" * (CAVE_HDR + code_len))]


def write_atomic(exe, buf):
    tmp = exe + ".tmp"
    with open(tmp, "wb") as f:
        f.write(buf)
    shutil.copymode(exe, tmp)
    os.replace(tmp, exe)  # new inode: a running game keeps the old image mapped


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", help="default: <STALKER2_FOLDER>/" + EXE_IN_GAME_FOLDER + ", else found via Steam")
    ap.add_argument("action", choices=["check", "apply", "revert"])
    a = ap.parse_args()
    exe = a.exe or default_exe()
    if not exe:
        sys.exit("game not found: pass --exe, or set STALKER2_FOLDER")

    data = open(exe, "rb").read()
    pe = PE(data)
    state, rolls = locate_hook(data)
    print(f"{state:8} 0x{pe.va(rolls):x}  offline duel: time-to-kill from live stats")
    if a.action == "check":
        if state == "vanilla":
            locate_imports(pe, rolls)  # fail early if apply would fail
            print("  all imports found; apply would work")
        return
    if (a.action == "apply") == (state == "patched"):
        print("already " + state)
        return

    edits = build_apply(pe, rolls) if a.action == "apply" else build_revert(pe, rolls)
    buf = bytearray(data)
    for o, b in edits:
        if not pe.in_text(o, len(b)):
            sys.exit("internal error: edit outside .text; exe not written")
        buf[o:o + len(b)] = b
    after, _ = locate_hook(bytes(buf))
    if after != ("patched" if a.action == "apply" else "vanilla"):
        sys.exit("internal error: result does not match the expected pattern; exe not written")
    if a.action == "apply":
        bak = exe + BACKUP_SUFFIX
        if not os.path.exists(bak):
            shutil.copy2(exe, bak)
            print(f"backup: {bak}")
    write_atomic(exe, buf)
    print(("patched " if a.action == "apply" else "reverted ") + exe)


if __name__ == "__main__":
    main()
