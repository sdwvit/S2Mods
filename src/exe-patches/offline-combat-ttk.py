#!/usr/bin/env python3
"""Patch the retail Stalker2-Win64-Shipping.exe so offline A-Life duels are decided by the units'
live stats (HP, armor, weapon, medkits, grenades), and the winner keeps the damage it took.

Vanilla (OfflineCombatSatisfier, the "Counterattack!" duel): attacker and target each roll
rand(0..OfflineCombatWeight), the higher roll wins, a tie is a coin flip, the loser dies and the
winner is untouched. The weight is a fixed number per NPC type, so loadouts never matter.

The patch replaces the two rolls (163 bytes) with a call into a code cave placed in unused int3
padding of .text. The cave (offline-combat-ttk/cave.c, entry.S) computes time-to-kill:
    effHP  = HP + 50 * medkits (<= 5)
    dmg    = BaseDamage * coef_enemy ^ (ArmorPiercing - Strike protection_enemy) * rank accuracy
             (0.6/0.7/0.8/0.9); with no weapon (mutants): the strongest attack ability's
             Damage * coef_enemy ^ (its ArmorPiercing - protection_enemy), baked per ObjPrototype SID
             from the GameLite cfgs by offline-combat-ttk/gen_attacks.py; not in that table:
             16 * (1 - 0.1 * protection_enemy)
    dmg   *= OfflineCombatWeight / 10 * rand(0.75 .. 1.25)   (NPCBase = 10, Cat 25, Chimera 75)
    burst  = 40 * grenades (<= 3), halved against mutants
    TTK    = max(0, effHP_enemy - burst) / dmg;  shorter TTK wins
    winner HP -= burst_loser + dmg_loser * TTK_winner  (medkits absorb first; HP stays >= 1)
and hands the result back as the two "rolls", so the vanilla kill/log code runs unchanged.
Inventory is read only; nothing is consumed.

Every game address the cave uses (6 functions, 3 data pools) is found by byte pattern, so small
updates still apply; a mismatch stops the script without writing. The struct offsets inside the
cave (unit HP 0x148, inventory 0x678, item proto type 0xd0, prototype SID 0xc, ...) are from the Nov 2026 build.

Usage:
  offline-combat-ttk.py [--exe PATH] check|apply|revert
Without --exe the exe is found under STALKER2_FOLDER (environment, else the repo .env),
else in the Steam libraries. apply writes <exe>.bak-offline-ttk once (the file before this patch),
then atomically replaces the exe. revert puts the original roll bytes back (kept inside the cave
header) and refills the cave with int3, so other exe patches stay intact. Steam "Verify integrity"
also restores the original. Rebuild the embedded cave with offline-combat-ttk/build.sh.
"""
